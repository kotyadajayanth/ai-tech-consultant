import { z } from "zod";

export const CATEGORIES = ["how_to", "troubleshooting", "project_request", "refund_cancellation", "complaint", "quote_request", "follow_up", "other"] as const;
export type Category = (typeof CATEGORIES)[number];
export const RISKS = ["low", "medium", "high"] as const;

/** Categories that can NEVER be sent without a human, whatever the approval streak says. */
export const NEVER_AUTONOMOUS: readonly Category[] = ["refund_cancellation", "complaint", "quote_request", "project_request"];

export const ClassificationSchema = z.object({
  category: z.enum(CATEGORIES),
  summary: z.string().min(1),
  risk: z.enum(RISKS),
  urgent: z.boolean(),
});
export type Classification = z.infer<typeof ClassificationSchema>;

export const DraftSchema = z.object({
  reply: z.string().min(1),
  sources_used: z.array(z.string()),
  needs_human: z.boolean(),
  follow_up_date: z.string().nullable(),
  next_action: z.string(),
});
export type DraftOut = z.infer<typeof DraftSchema>;

export interface KnowledgeSource { title: string; url: string; relevance: number; kind: string }
export interface KnowledgeAnswer {
  status: "answered" | "insufficient_evidence";
  answer: string;
  sources: KnowledgeSource[];
  needs_human: boolean;
  escalation_id: number | null;
}

export interface Email { id: string; from: string; subject: string; body: string; receivedAt: string }

export type ReviewStatus = "pending" | "sent" | "rejected" | "expert";
export interface Draft {
  id: string;
  email: Email;
  classification: Classification;
  knowledge: { available: boolean; answer?: KnowledgeAnswer; error?: string };
  reply: string;                 // text generated by the model (never changes after creation)
  sourcesUsed: string[];
  needsHuman: boolean;
  nextAction: string;
  followUpDate: string | null;
  promptVersion: string;
  model: string;
  autoSent: boolean;
  status: ReviewStatus;
  finalReply?: string;           // what was really sent
  correctionReason?: string;
  createdAt: string;
  resolvedAt?: string;
}
